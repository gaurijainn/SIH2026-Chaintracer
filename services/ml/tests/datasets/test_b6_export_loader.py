"""B7.3: the B6 -> B7 feature-export bridge loader.

Fixture: tests/fixtures/datasets/mule_features_sample.json, a copy of the repo-root
data/ml-exports/mule_features_sample.json checked-in fixture generated by
scripts/export-mule-features-fixture.mts from B6's real production computeMuleFeatures (see
apps/api/src/mule/export/exportFeatures.fixture.test.ts for the Node-side golden-file test over the
same file). Nothing here recomputes a B6 feature -- these tests only check the export was read,
validated and repackaged faithfully.
"""
import json
from pathlib import Path

import pytest

from app.datasets import BenchmarkDataset, Chain, DatasetLabel, DatasetPurpose, TrainingDataset, require_benchmark, require_training
from app.datasets.loaders import B6ExportLoader
from app.features import FEATURE_NAMES

FIXTURE = Path(__file__).parent.parent / "fixtures" / "datasets" / "mule_features_sample.json"


def test_loads_into_a_training_dataset_with_every_row():
    ds = B6ExportLoader().load(FIXTURE)
    assert isinstance(ds, TrainingDataset)
    assert ds.manifest.purpose == DatasetPurpose.TRAINING
    raw = json.loads(FIXTURE.read_text())
    assert len(ds.rows) == len(raw["rows"])


def test_manifest_version_comes_from_the_export_files_own_dataset_version():
    ds = B6ExportLoader().load(FIXTURE)
    raw = json.loads(FIXTURE.read_text())
    assert ds.manifest.version == raw["datasetVersion"]
    assert ds.manifest.local_path == str(FIXTURE)


def test_chain_and_identifier_are_preserved_from_the_export():
    ds = B6ExportLoader().load(FIXTURE)
    by_id = {r.identifier: r for r in ds.rows}
    assert by_id["TMULE1FULLYKNOWNADDRESS0000000001"].chain == Chain.TRON
    assert by_id["0xflags4multipleflagsandcrosscase4"].chain == Chain.ETH


def test_known_label_is_preserved_and_unknown_label_becomes_explicit_unknown():
    ds = B6ExportLoader().load(FIXTURE)
    by_id = {r.identifier: r for r in ds.rows}
    assert by_id["TMULE1FULLYKNOWNADDRESS0000000001"].label == DatasetLabel.HIGH_RISK
    assert by_id["0xflags4multipleflagsandcrosscase4"].label == DatasetLabel.LICIT
    # this row's export has label: null -- must become UNKNOWN, never a guessed illicit/licit/high_risk
    assert by_id["TFRESH2NOOUTBOUNDYET00000000000002"].label == DatasetLabel.UNKNOWN


def test_numeric_features_are_preserved_exactly_from_the_export():
    ds = B6ExportLoader().load(FIXTURE)
    row = next(r for r in ds.rows if r.identifier == "TMULE1FULLYKNOWNADDRESS0000000001")
    assert row.features["dwell_median_min"] == 20
    assert row.features["fan_out_1h"] == 1
    assert row.features["passthrough_ratio"] == 0.985
    assert row.features["shared_mule_cps"] == 3
    assert row.features["cross_case_count"] == 2


def test_boolean_feature_is_encoded_as_zero_or_one():
    ds = B6ExportLoader().load(FIXTURE)
    by_id = {r.identifier: r for r in ds.rows}
    assert by_id["TMULE1FULLYKNOWNADDRESS0000000001"].features["trx_dust_usdt"] == 1.0
    assert by_id["TFRESH2NOOUTBOUNDYET00000000000002"].features["trx_dust_usdt"] == 0.0


def test_activator_label_is_deterministically_hashed_when_present_and_carried_raw_in_extra():
    ds = B6ExportLoader().load(FIXTURE)
    row = next(r for r in ds.rows if r.identifier == "TMULE1FULLYKNOWNADDRESS0000000001")
    assert isinstance(row.features["activator_label_hash"], float)
    assert row.extra["activator_label"] == "exchange"


def test_missing_activator_label_hash_is_omitted_not_invented_as_zero():
    ds = B6ExportLoader().load(FIXTURE)
    row = next(r for r in ds.rows if r.identifier == "TFRESH2NOOUTBOUNDYET00000000000002")
    assert "activator_label_hash" not in row.features
    assert row.extra["activator_label"] is None


def test_external_flags_count_is_always_present_and_raw_list_is_in_extra():
    ds = B6ExportLoader().load(FIXTURE)
    row = next(r for r in ds.rows if r.identifier == "0xflags4multipleflagsandcrosscase4")
    assert row.features["external_flags_count"] == 3.0
    assert row.extra["external_flags"] == ["fraudTransaction", "stablecoinBlacklist", "reported"]


def test_null_numeric_features_are_omitted_and_listed_in_missing_features_not_defaulted():
    ds = B6ExportLoader().load(FIXTURE)
    row = next(r for r in ds.rows if r.identifier == "TNOMETA3NOADDRESSPROFILE0000000003")
    assert "age_at_taint_days" not in row.features
    assert "hops_from_victim" not in row.features
    assert "sanction_exposure" not in row.features
    assert set(row.extra["missing_features"]) >= {"age_at_taint_days", "hops_from_victim", "hops_to_vasp", "sanction_exposure"}


def test_rejects_an_export_file_whose_feature_order_does_not_match_b71(tmp_path):
    bad = {
        "datasetVersion": "v1",
        "generatedAt": "2026-09-01T00:00:00.000Z",
        "featureOrder": ["fan_out_1h", "dwell_median_min"] + list(FEATURE_NAMES[2:]),  # first two swapped
        "rows": [],
    }
    p = tmp_path / "bad_order.json"
    p.write_text(json.dumps(bad))
    with pytest.raises(ValueError, match="featureOrder"):
        B6ExportLoader().load(p)


def test_rejects_a_row_with_an_unknown_feature_name(tmp_path):
    bad_row = json.loads(FIXTURE.read_text())
    bad_row["rows"][0]["features"]["not_a_real_feature"] = 1.0
    p = tmp_path / "bad_feature.json"
    p.write_text(json.dumps(bad_row))
    with pytest.raises(ValueError):
        B6ExportLoader().load(p)


def test_a_b6_export_dataset_is_usable_as_training_data():
    ds = B6ExportLoader().load(FIXTURE)
    assert require_training([ds]) == [ds]


def test_a_b6_export_dataset_can_never_enter_the_benchmark_path():
    ds = B6ExportLoader().load(FIXTURE)
    assert not isinstance(ds, BenchmarkDataset)
    with pytest.raises(ValueError, match="b6-mule-features"):
        require_benchmark([ds])
